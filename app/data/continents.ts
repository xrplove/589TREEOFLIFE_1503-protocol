export function getContinent(id: string): Continent | undefined {
  return CONTINENTS.find((c) => c.id === id)
}

/** Convert ISO Alpha-2 country code to flag emoji. */
export function flagEmoji(code: string): string {
  const upper = code.toUpperCase()
  // Special case: XK (Kosovo) has no official emoji yet
  if (upper === 'XK') return '🏳'
  const codePoints = upper.split('').map((c) => 0x1f1e6 - 65 + c.charCodeAt(0))
  return String.fromCodePoint(...codePoints)
}
