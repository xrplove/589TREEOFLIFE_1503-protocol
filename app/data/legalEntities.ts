// Country-specific legal entity types and document requirements.
// For v1 we cover the most active trade countries in detail; the rest
// use a sensible generic set so registration always works.

export type EntityKind = 'individual' | 'company'

/** Validation state of an entity-specific document list.
    'draft'    → list assembled from public sources, NOT yet validated by a
                 lawyer. UI shows a "BORRADOR · pendiente revisión legal" badge.
    'verified' → list signed off by external counsel; no badge shown.
    Default (when omitted) is 'verified', i.e. the universal kind-based list
    we already had. */
export type DocsStatus = 'draft' | 'verified'

export type LegalEntity = {
  code: string // short local code or abbreviation
  nameLocal: string // entity name in local language / official form
  nameES: string // Spanish description (shown to Spanish-speaking registrants)
  nameEN?: string // English description (shown to non-Spanish registrants; falls back to nameLocal)
  forSize?: 'micro' | 'small' | 'medium' | 'large' | 'any'
  /** Whether this is an individual person (autónomo, sole trader) or
      an incorporated entity (LLC, AG, S.A.). Drives which document set
      is requested at registration. */
  kind: EntityKind
  /** Extra documents that THIS entity requires beyond the universal
      kind-based list (e.g. cooperative needs proof of approval by the
      general assembly; large SA needs an audited annual report). */
  specificDocs?: string[]
  /** If true, replace the kind-based base entirely with `specificDocs`
      instead of appending. Useful when the standard "certificate of
      incorporation" doesn't apply at all (e.g. cooperative is registered
      in a different registry). */
  specificDocsReplace?: boolean
  /** Validation status of `specificDocs`. Omit for entities without
      `specificDocs`. */
  docsStatus?: DocsStatus
  /** ISO date of the last legal review (only meaningful for 'verified'). */
  lastReviewedAt?: string
  /** Free text — name of the lawyer / firm that signed off. */
  reviewedBy?: string
}

export type CountryLegalSetup = {
  /** ISO Alpha-2 code, lowercase */
  code: string
  /** Country name in Spanish */
  nameES: string
  /** Local registry / equivalent of "Registro Mercantil" */
  registry: string
  /** Tax ID label as locals know it (e.g. "CIF", "USt-IdNr", "EIN") */
  taxIdLabel: string
  /** Legal entity types available in this country */
  entities: LegalEntity[]
  /** Documents 1503 will ask for in addition to the universal ones */
  extraDocs: string[]

  // ── Capa 0 KYB · ADR 0022 · autoridades con FUENTE OFICIAL VERIFICADA ──
  // Todos los campos opcionales: se rellenan país a país por lotes, cada URL
  // verificada por web contra la fuente oficial (canon: nunca de memoria del
  // modelo). Lo no verificado se deja vacío / 'pending-verification', JAMÁS
  // se inventa. La aplicabilidad y suficiencia es subject_to_expert.
  /** URL oficial del registro mercantil/empresarial (trazable). */
  registryUrl?: string
  /** Autoridad fiscal nacional (nombre corto). */
  taxAuthority?: string
  /** URL oficial de la autoridad fiscal. */
  taxAuthorityUrl?: string
  /** Base legal del KYB de ese país (norma AML + registro mercantil). */
  kybLegalBasis?: string
  /** Estado de verificación de las fuentes KYB de este país. */
  kybStatus?: 'subject_to_expert' | 'pending-verification'
  /** ISO date (AAAA-MM-DD) de la última verificación de las URLs oficiales. */
  kybVerifiedAt?: string
}

