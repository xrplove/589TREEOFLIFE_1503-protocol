for (const [c, forms] of Object.entries(COMPLETENESS_EXTRA)) {
  const setup = DETAILED[c]
  if (!setup) continue
  for (const f of forms) {
    if (!setup.entities.some((e) => e.code === f.code)) setup.entities.push({ ...f })
  }
}

/** Get the legal setup for a country by ISO Alpha-2 code (case-insensitive). */
export function getLegalSetup(code: string): CountryLegalSetup {
  const lower = code.toLowerCase()
  if (DETAILED[lower]) return DETAILED[lower]
  // Generic fallback — entities + universal docs only.
  return {
    code: lower,
    nameES: '', // filled in by caller from continents.ts
    registry: 'Registro mercantil local equivalente',
    taxIdLabel: 'Tax ID local',
    entities: GENERIC_ENTITIES,
    extraDocs: [],
  }
}

export function getRequiredDocs(code: string): string[] {
  const setup = getLegalSetup(code)
  return [...UNIVERSAL_DOCS, ...setup.extraDocs]
}
