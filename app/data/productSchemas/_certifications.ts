// Registry de certificaciones referenciables por las fichas sectoriales.
//
// Cada entrada describe un certificado emitido por una entidad oficial
// reconocida (organismo · norma internacional · colegio profesional). Las
// fichas referencian estos certificados por `certification_id`.
//
// CRÍTICO: este registry NO valida que un certificado exista realmente. Esa
// validación se hace contra el emisor (registro oficial · KYC profesional
// Fase 3a-bis · o subida manual con revisión por Operador).
//
// Validación experta sectorial pendiente: las entradas marcadas con
// `status: 'draft'` necesitan revisión por experto del sector antes de
// pasar a 'validated'. Mismo patrón que `legalEntities.ts` y `actorGroups.ts`.

import type { LocalizedLabel } from '@/app/data/actorGroups'

/** Estado de validación de una entrada del registry de certificaciones.
 *
 *  4 estados alineados con `ProductSchemaStatus` y `TaxonomyStatus` (ADR 0011
 *  Audit-Ready by Design):
 *
 *  - 'draft': borrador · pendiente revisión.
 *  - 'subject_to_expert': construido siguiendo norma oficial trazable (campo
 *    `reference_url` apunta a EUR-Lex / iso.org / une.org) pero pendiente
 *    validación experta sectorial (organismo notificado · colegio profesional ·
 *    auditoría jurídica).
 *  - 'validated': revisado por experto autorizado · apto producción.
 *  - 'deprecated': sustituido por otra versión o normativa derogada. */
export type CertificationStatus = 'draft' | 'subject_to_expert' | 'validated' | 'deprecated'

/** Aplicabilidad geográfica de la certificación. */
export type CertificationScope =
  | 'global'          // ISO · UCP · INCOTERMS · IATA · IMO
  | 'eu'              // UE · EFTA
  | 'national'        // país específico (e.g. AEMPS España · FDA US)
  | 'sectoral'        // colegio profesional o gremio del sector

/** Tipo de actor que emite y/o requiere el certificado. */
export type CertificationCategory =
  | 'quality_management'   // ISO 9001 · ISO 14001
  | 'trade_finance'        // UCP 600 · ISBP 821
  | 'transport_safety'     // ADR · IMDG · IATA DGR · TAPA
  | 'customs_authorization'// AEO · OEA
  | 'shipping_docs'        // Bill of Lading · CMR · Air Waybill
  | 'incoterms'            // INCOTERMS 2020
  | 'food_safety'          // HACCP · IFS · BRC · ISO 22000 · FSSC 22000 · GlobalG.A.P.
  | 'food_quality'         // DOP · IGP · ETG · Eco UE · Halal · MSC · ASC · Fairtrade
  | 'real_estate'          // Cédula habitabilidad · IEE · CEE
  | 'professional_license' // Colegio profesional aplicable
  | 'environmental'        // EMAS · ISO 14001 · sello CO2 · CBAM · REACH · RoHS · ESPR
  | 'industrial_compliance'// PED · EN 1090 · EN 10204 · EN 13445 · EN 12952/53 · Maquinaria · ATEX · ISO 3834 · IATF · AS 9100
  | 'textile_sustainability'// OEKO-TEX · GOTS · GRS · RCS · OCS · Bluesign · Cradle to Cradle · Better Cotton · LWG · ZDHC
  | 'product_labeling'     // Reg. UE 1007/2011 textil · etiquetado FIC · ecolabels

/** Definición canónica de una certificación. */
export type CertificationDefinition = {
  /** ID universal del certificado (referenciable desde fichas). */
  id: string
  /** Nombre canónico × 8 idiomas. */
  name: LocalizedLabel
  /** Descripción corta × 8 idiomas. */
  description: LocalizedLabel
  /** Categoría funcional. */
  category: CertificationCategory
  /** Alcance geográfico. */
  scope: CertificationScope
  /** Códigos ISO 3166-1 alpha-2 donde aplica si scope es 'national' o 'eu'.
   *  Para 'global' o 'sectoral' puede dejarse vacío. */
  countries?: string[]
  /** Norma o referencia oficial (e.g. 'ISO 9001:2015' · 'Reg. UE 952/2013'). */
  reference?: string
  /** URL pública del documento normativo si disponible. */
  reference_url?: string
  /** Entidad emisora habitual (organismo · auditor acreditado · colegio). */
  typical_issuer?: string
  /** Duración típica del certificado en años (0 = indefinido). */
  validity_years?: number
  /** Estado de validación de esta entrada del registry. */
  status: CertificationStatus
}

