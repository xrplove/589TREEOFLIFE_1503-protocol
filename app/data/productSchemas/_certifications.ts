/** Lookup por ID. Retorna `null` si no existe. */
export function getCertification(id: string): CertificationDefinition | null {
  return CERTIFICATIONS.find((c) => c.id === id) ?? null
}

/** Filtra certificaciones aplicables a un sector dado. Retorna por categoría. */
export function certificationsByCategory(
  category: CertificationCategory,
): CertificationDefinition[] {
  return CERTIFICATIONS.filter((c) => c.category === category)
}

